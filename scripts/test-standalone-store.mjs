// Run with `node --experimental-default-type=module scripts/test-standalone-store.mjs`.
import assert from 'node:assert/strict';
const storage=new Map();
globalThis.localStorage={getItem:k=>storage.get(k)??null,setItem:(k,v)=>storage.set(k,v),removeItem:k=>storage.delete(k)};
globalThis.window={addEventListener:()=>{}};
const {createStandaloneAPI}=await import('../internal/server/ui/js/standalone-store.js');
const store=createStandaloneAPI();
const api=store.api;
let s=await api('/state');assert.equal(s.templates.length,0);
const first=await api('/templates','POST',{name:'Pause',duration:'10m',group:'Arbeit',shortcut:'1',notify:true,alarm:{tone:'gong',repeat:'until_ack',visual:true,system:false}});
const second=await api('/templates','POST',{name:'Pause',duration:'5m',group:'Sport',shortcut:'0',sound:false});
await assert.rejects(()=>api('/templates','POST',{name:'Fehler',duration:'3m',shortcut:'1'}),/bereits vergeben/);
await assert.rejects(()=>api('/templates','POST',{name:'Fehler',duration:'3m',shortcut:'F'}),/Schnellstart/);
assert.equal(first.browser_only,true);
assert.equal(first.alarm.tone,'gong');
assert.equal((await api('/state')).groups.join(','),'Arbeit,Sport');
await assert.rejects(()=>api('/templates','POST',{name:'Pause',duration:'2m',group:'Arbeit'}),/Name/);
const third=await api('/templates','POST',{name:'Eier',duration:'7m',group:''});
s=await api('/state');assert.deepEqual(s.templates.map(t=>t.id),[first.id,second.id,third.id]);
await assert.rejects(()=>api('/templates/order','PUT',{ids:[third.id,second.id,first.id]}),/Gruppe/);
await api('/groups/order','PUT',{groups:['Sport','Arbeit']});
s=await api('/state');assert.deepEqual(s.groups,['Sport','Arbeit']);
await api('/groups/Arbeit','PUT',{name:'Büro'});
s=await api('/state');assert.deepEqual(s.groups,['Sport','Büro']);
await api('/templates/'+encodeURIComponent(first.id),'PUT',{name:'Pause lang',duration:'15m',group:'Sport',shortcut:'1',notify:false});
await assert.rejects(()=>api('/templates/'+encodeURIComponent(first.id),'PUT',{name:'Pause lang',duration:'15m',group:'Sport',shortcut:'0'}),/bereits vergeben/);
s=await api('/state');assert.deepEqual(s.groups,['Sport']);
const backup=store.exportBackup([]);assert.equal(backup.version,1);
const valid=store.importBackup(backup);assert.equal(valid.favorites.length,3);assert.equal(valid.favorites.find(f=>f.id===first.id).shortcut,'1');
await api('/templates/'+encodeURIComponent(second.id),'DELETE');
s=await api('/state');assert.equal(s.templates.length,2);
const reopened=createStandaloneAPI();assert.equal((await reopened.api('/state')).templates.length,2);
console.log('Standalone store tests passed (groups, order, shortcuts, conflicts, persistence, backup)');
